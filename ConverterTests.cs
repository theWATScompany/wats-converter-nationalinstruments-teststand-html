using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Virinco.WATS.Interface;
using Xunit;
using Xunit.Abstractions;
using WATS.Testing;
using Virinco.WATS.Converter.NI.TestStand;

namespace NI_TestStand_HTML.Tests
{
    // TextConverterBase: ImportReport() returns null (submit is internal).
    // Only ConvertOnly mode applies.
    public class ConverterTests : TextConverterTestBase
    {
        public ConverterTests(ITestOutputHelper output) : base(output) { }
        protected override IReportConverter_v2 CreateConverter() => new TeststandHTMLConverter();
        // Only scan top-level Data/ files; the 2010/ subfolder uses a different converter.
        protected override IEnumerable<string> GetDataFiles()
        {
            var dataDir = System.IO.Path.Combine(AppContext.BaseDirectory, DataDirectory);
            if (!System.IO.Directory.Exists(dataDir)) return Enumerable.Empty<string>();
            return System.IO.Directory.GetFiles(dataDir, "*.html", System.IO.SearchOption.TopDirectoryOnly)
                .OrderBy(f => f);
        }

        [Fact, Trait("TestMode", "ConvertOnly")]
        public void ConvertOnly_AllFiles() => RunAllFiles();
    }

    // Tests for the older TestStand HTML 3.2 format (circa 2010).
    public class ConverterTests_2010 : TextConverterTestBase
    {
        public ConverterTests_2010(ITestOutputHelper output) : base(output) { }
        protected override IReportConverter_v2 CreateConverter() => new TeststandHTMLConverter_2010();
        protected override string DataDirectory => "Data/2010";

        [Fact, Trait("TestMode", "ConvertOnly")]
        public void ConvertOnly_AllFiles() => RunAllFiles();
    }

    /// <summary>
    /// Tests for TestStand HTML generated by the ATML-based stylesheet
    /// (e.g. Hitachi's tr6_horizontal.xsl).
    /// This converter implements IReportConverter_v2 and returns the Report object directly
    /// (the WATS Client submits it externally) — use ConverterTestBase, not TextConverterTestBase.
    /// </summary>
    public class ConverterTests_ATML : ConverterTestBase
    {
        public ConverterTests_ATML(ITestOutputHelper output) : base(output) { }
        protected override IReportConverter_v2 CreateConverter() => new TeststandATMLHtmlConverter();
        protected override string DataDirectory => "Data/ATML";
        protected override IEnumerable<string> GetDataFiles()
        {
            var dir = System.IO.Path.Combine(AppContext.BaseDirectory, DataDirectory);
            if (!System.IO.Directory.Exists(dir)) return Enumerable.Empty<string>();
            return System.IO.Directory.GetFiles(dir, "*.html", System.IO.SearchOption.TopDirectoryOnly)
                .OrderBy(f => f);
        }

        [Fact, Trait("TestMode", "ConvertOnly")]
        public void ConvertOnly_AllFiles() => RunAllFiles(TestMode.ConvertOnly);

        [Fact, Trait("TestMode", "ConvertAndValidate")]
        public void ConvertAndValidate_AllFiles() => RunAllFiles(TestMode.ConvertAndValidate);

        [Fact, Trait("TestMode", "ConvertAndSubmit"), Trait("RequiresServer", "true")]
        public void ConvertAndSubmit_AllFiles() => RunAllFiles(TestMode.ConvertAndSubmit);
    }
}
